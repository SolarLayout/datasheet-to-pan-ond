"""Bulk export of database records to YAML specs (and optionally PAN/OND files)."""

from __future__ import annotations

import csv
import datetime as dt
import os
import re
from collections.abc import Iterable
from concurrent.futures import ProcessPoolExecutor
from dataclasses import dataclass, field
from pathlib import Path

import pandas as pd

from datasheet_to_pan_ond._version import __version__
from datasheet_to_pan_ond.inverter_fit import fit_inverter
from datasheet_to_pan_ond.io import dump_spec, load_inverter, load_module
from datasheet_to_pan_ond.module_fit import fit_module
from datasheet_to_pan_ond.sources import cec
from datasheet_to_pan_ond.writers import write_ond, write_pan

REPORT_NAME = "_import_report.csv"
REVIEW_MARKER = "VERIFY"


@dataclass
class ExportRow:
    """One line of the import report."""

    name: str
    status: str  # "exported", "built", "skipped", "build_failed", "build_refused"
    yaml_file: str = ""
    output_file: str = ""
    needs_review: bool = False
    detail: str = ""
    warnings: list[str] = field(default_factory=list)


def slugify(name: str) -> str:
    """Filesystem-safe file stem for a product name."""
    slug = re.sub(r"[^A-Za-z0-9._-]+", "_", name).strip("._")
    return slug[:150] or "unnamed"


def _unique(stem: str, used: set[str]) -> str:
    candidate, i = stem, 2
    while candidate.lower() in used:
        candidate = f"{stem}_{i}"
        i += 1
    used.add(candidate.lower())
    return candidate


def _header(kind: cec.Kind, name: str, library: str, source: str) -> list[str]:
    return [
        f"Generated by datasheet-to-pan-ond {__version__} on {dt.date.today().isoformat()}",
        f"Source: CEC {kind[:-1]} list via NREL SAM library {library}".rstrip(),
        f"        {source_label(source)}",
        f"Record: {name}",
        "Inferred / assumed values are listed under provenance_notes.",
        "Check them against the manufacturer datasheet before relying on the output.",
    ]


def source_label(source: str) -> str:
    """Public description of the data source (never a local absolute path)."""
    for kind, path in cec.CACHE_FILES.items():
        if Path(source).name == path:
            return cec.SAM_URLS[kind]
    return Path(source).name


def _build(args: tuple[str, str, str, bool]) -> tuple[str, list[str], str]:
    """Worker: fit one YAML spec and write the PAN/OND file. Returns (status, warnings, detail)."""
    kind, yaml_path, out_path, strict = args
    try:
        if kind == "modules":
            mres = fit_module(load_module(yaml_path))
            warns = mres.warnings
            if strict and warns:
                return "build_refused", warns, "warnings present (--strict)"
            write_pan(mres, out_path)
        else:
            ires = fit_inverter(load_inverter(yaml_path))
            warns = ires.warnings
            if strict and warns:
                return "build_refused", warns, "warnings present (--strict)"
            write_ond(ires, out_path)
    except Exception as exc:  # report and continue in bulk mode
        return "build_failed", [], f"{type(exc).__name__}: {exc}"
    return "built", warns, ""


def export_records(
    kind: cec.Kind,
    rows: pd.DataFrame,
    out_dir: str | Path,
    *,
    library: str = "",
    source: str = "",
    build: bool = False,
    strict: bool = False,
    jobs: int = 1,
) -> list[ExportRow]:
    """Convert ``rows`` to YAML specs in ``out_dir``; optionally build PAN/OND files.

    Writes ``_import_report.csv`` in ``out_dir`` and returns its rows.
    """
    out = Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)
    used: set[str] = set()
    report: list[ExportRow] = []
    to_build: list[tuple[int, tuple[str, str, str, bool]]] = []
    suffix = ".PAN" if kind == "modules" else ".OND"

    for _, row in rows.iterrows():
        conv = cec.convert(kind, row, library)
        if not conv.ok or conv.spec is None:
            report.append(ExportRow(conv.name, "skipped", detail=conv.error or ""))
            continue
        stem = _unique(slugify(conv.name), used)
        yaml_path = dump_spec(
            conv.spec, out / f"{stem}.yaml", _header(kind, conv.name, library, source)
        )
        review = any(REVIEW_MARKER in n for n in conv.notes)
        report.append(ExportRow(conv.name, "exported", yaml_path.name, needs_review=review))
        if build:
            to_build.append(
                (len(report) - 1, (kind, str(yaml_path), str(out / f"{stem}{suffix}"), strict))
            )

    if to_build:
        args = [a for _, a in to_build]
        n_jobs = jobs if jobs > 0 else (os.cpu_count() or 1)
        if n_jobs == 1 or len(args) < 8:
            results: Iterable[tuple[str, list[str], str]] = map(_build, args)
        else:
            with ProcessPoolExecutor(max_workers=n_jobs) as pool:
                results = list(pool.map(_build, args, chunksize=16))
        for (idx, a), (status, warns, detail) in zip(to_build, results, strict=True):
            row_ = report[idx]
            row_.status, row_.warnings, row_.detail = status, warns, detail
            if status == "built":
                row_.output_file = Path(a[2]).name

    write_report(report, out / REPORT_NAME)
    return report


def write_report(rows: list[ExportRow], path: Path) -> None:
    with path.open("w", newline="", encoding="utf-8") as fh:
        w = csv.writer(fh)
        w.writerow(
            ["name", "status", "yaml_file", "output_file", "needs_review", "detail", "warnings"]
        )
        for r in rows:
            w.writerow(
                [
                    r.name,
                    r.status,
                    r.yaml_file,
                    r.output_file,
                    "yes" if r.needs_review else "",
                    r.detail,
                    " | ".join(r.warnings),
                ]
            )
