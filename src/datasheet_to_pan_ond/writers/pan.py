"""Build a PVsyst ``.PAN`` (PV module) file from a module fit.

Layout and fixed values mirror a PVsyst 7.2 export
(``tests/data/reference/ET-M772BH550GL.PAN``). Keys we have no datasheet
basis for are filled with the PVsyst defaults seen in that file and listed
in ``PVSYST_DEFAULTS`` so they are easy to audit.
"""

from __future__ import annotations

import datetime as dt
from pathlib import Path

from datasheet_to_pan_ond._version import __version__
from datasheet_to_pan_ond.models import ModuleDatasheet
from datasheet_to_pan_ond.module_fit import ModuleFitResult
from datasheet_to_pan_ond.writers.pvsyst_format import (
    DEFAULT_FORMAT,
    Blank,
    FileFormat,
    Section,
    cubic_profile,
    num,
    price_date,
    pvobject,
    remarks,
    sanitize,
    write,
)

PAN_VERSION = "7.2"
#: Opaque PVsyst bit flags, copied from PVsyst 7.2 exports (semantics unknown).
FLAGS_MODULE = "$00900243"
FLAGS_COMMERCIAL = "$0041"
FLAGS_IAM = "$00"
IAM_LAST_COMPILE = "$B18D"

#: Values written verbatim when the datasheet has no equivalent.
#: Reverse-bias (ARev, BRev, ...) and spectral values are PVsyst defaults.
PVSYST_DEFAULTS: dict[str, str] = {
    "FrontSurface": "fsARCoating",
    "GRef": "1000",
    "TRef": "25.0",
    "Absorb": "0.90",
    "ARev": "3.200",
    "BRev": "16.716",
    "RDiode": "0.010",
    "VRevDiode": "-0.70",
    "AirMassRef": "1.500",
    "SandiaAMCorr": "50.000",
}


def build_pan(result: ModuleFitResult, now: dt.datetime | None = None) -> Section:
    ds = result.datasheet
    p = result.params

    root = pvobject("PVObject_", "pvModule")
    root.add("Version", PAN_VERSION).add("Flags", FLAGS_MODULE)
    root.items.append(Blank())
    root.items.append(_commercial(ds, result, now))
    root.items.append(Blank())

    d = PVSYST_DEFAULTS
    root.add("Technol", ds.technology.value)
    root.add("NCelS", ds.cells_in_series).add("NCelP", ds.cells_in_parallel)
    root.add("NDiode", ds.bypass_diodes)
    if ds.half_cell:
        root.add("SubModuleLayout", "slTwinHalfCells")
    root.add("FrontSurface", d["FrontSurface"])
    root.add("GRef", d["GRef"]).add("TRef", d["TRef"])
    root.add("PNom", num(ds.p_nom, 1))
    root.add("PNomTolUp", num(ds.p_nom_tol_up_pct, 2))
    root.add_opt("BifacialityFactor", None if ds.bifaciality is None else num(ds.bifaciality, 3))
    root.add("Isc", num(ds.isc, 3)).add("Voc", num(ds.voc, 2))
    root.add("Imp", num(ds.imp, 3)).add("Vmp", num(ds.vmp, 2))
    # PVsyst units: mA/K, mV/K, %/K
    root.add("muISC", num(ds.isc * ds.temp_coeff_isc_pct * 10.0, 2))
    root.add("muVocSpec", num(ds.voc * ds.temp_coeff_voc_pct * 10.0, 1))
    root.add("muPmpReq", num(ds.temp_coeff_pmax_pct, 3))
    root.add("RShunt", num(p.R_sh_ref, 1))
    root.add("Rp_0", num(p.R_sh_0, 1))
    root.add("Rp_Exp", num(p.R_sh_exp, 2))
    root.add("RSerie", num(p.R_s, 4))
    root.add("Gamma", num(p.gamma_ref, 4))
    root.add("muGamma", num(p.mu_gamma, 6))
    root.add_opt("VMaxIEC", None if ds.v_max_iec is None else num(ds.v_max_iec, 0))
    root.add_opt("VMaxUL", None if ds.v_max_ul is None else num(ds.v_max_ul, 0))
    for key in ("Absorb", "ARev", "BRev", "RDiode", "VRevDiode", "AirMassRef"):
        root.add(key, d[key])
    root.add_opt("CellArea", None if ds.cell_area_cm2 is None else num(ds.cell_area_cm2, 1))
    root.add("SandiaAMCorr", d["SandiaAMCorr"])

    if ds.iam_profile:
        root.items.append(Blank())
        iam = pvobject("PVObject_IAM", "pvIAM")
        iam.add("Flags", FLAGS_IAM).add("IAMMode", "UserProfile")
        pts = [(num(pt.angle_deg, 1), num(pt.iam, 5)) for pt in ds.iam_profile]
        iam.items.append(cubic_profile("IAMProfile", pts, mode=3, last_compile=IAM_LAST_COMPILE))
        root.items.append(iam)
    return root


def _commercial(ds: ModuleDatasheet, result: ModuleFitResult, now: dt.datetime | None) -> Section:
    c = pvobject("PVObject_Commercial", "pvCommercial")
    c.add("Comment", sanitize(f"{ds.manufacturer} - generated from datasheet"))
    c.add("Flags", FLAGS_COMMERCIAL)
    c.add("Manufacturer", sanitize(ds.manufacturer)).add("Model", sanitize(ds.model))
    c.add("DataSource", sanitize(ds.data_source))
    c.add_opt("YearBeg", ds.year)
    dim = ds.dimensions
    c.add_opt("Width", None if dim.width_m is None else num(dim.width_m, 3))
    c.add_opt("Height", None if dim.height_m is None else num(dim.height_m, 3))
    c.add_opt("Depth", None if dim.depth_m is None else num(dim.depth_m, 3))
    c.add_opt("Weight", None if dim.weight_kg is None else num(dim.weight_kg, 3))
    c.add("NPieces", 100)
    c.add("PriceDate", price_date(now))
    c.items.append(remarks(provenance_lines(result.assumptions)))
    return c


def provenance_lines(assumptions: list[str]) -> list[str]:
    header = f"Generated by datasheet-to-pan-ond {__version__} from datasheet values (not measured)"
    return [header] + [f"Assumed: {a}" for a in assumptions]


def write_pan(
    result: ModuleFitResult,
    path: str | Path,
    fmt: FileFormat = DEFAULT_FORMAT,
    now: dt.datetime | None = None,
) -> Path:
    return write(build_pan(result, now), path, fmt)
