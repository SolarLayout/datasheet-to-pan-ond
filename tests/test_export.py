from __future__ import annotations

import csv
from pathlib import Path

import pytest
from pvlib.iotools import read_panond

from datasheet_to_pan_ond.cli import main
from datasheet_to_pan_ond.io import load_inverter, load_module
from datasheet_to_pan_ond.sources import cec
from datasheet_to_pan_ond.sources.export import REPORT_NAME, export_records, slugify
from tests.test_cec import INVERTERS, MODULES


def _report(out: Path) -> list[dict[str, str]]:
    with (out / REPORT_NAME).open(encoding="utf-8") as fh:
        return list(csv.DictReader(fh))


def test_slugify() -> None:
    assert slugify("SMA America: STP 20-US-50 {480V}") == "SMA_America_STP_20-US-50_480V"
    assert slugify("///") == "unnamed"


def test_export_modules_yaml_only(tmp_path: Path) -> None:
    rows = export_records("modules", cec.load("modules", MODULES), tmp_path, library="L")
    status = {r.name: r.status for r in rows}
    assert list(status.values()).count("exported") == 5
    assert list(status.values()).count("skipped") == 2
    report = _report(tmp_path)
    assert {r["needs_review"] for r in report} == {"yes", ""}
    for r in rows:
        if r.status == "exported":
            spec = load_module(tmp_path / r.yaml_file)  # YAML round-trips through the schema
            assert spec.provenance_notes
            assert (tmp_path / r.yaml_file).read_text().startswith("# Generated by")


@pytest.mark.parametrize("jobs", [1, 2])
def test_export_inverters_with_build(tmp_path: Path, jobs: int) -> None:
    df = cec.load("inverters", INVERTERS)
    big = df.loc[df.index.repeat(3)].reset_index(drop=True)  # 12 rows -> exercises the pool
    rows = export_records("inverters", big, tmp_path, build=True, jobs=jobs)
    assert all(r.status == "built" for r in rows)
    assert len({r.output_file for r in rows}) == 12  # duplicate names get unique files
    ond = read_panond(tmp_path / rows[0].output_file, encoding="utf-8-sig")["PVObject_"]
    assert ond["Converter"]["ProfilPIO"]["NPtsEff"] == 8
    assert load_inverter(tmp_path / rows[0].yaml_file).efficiency_curve is not None


def test_cli_cec_search_and_export(tmp_path: Path, capsys: pytest.CaptureFixture[str]) -> None:
    assert main(["cec", "search", "modules", "jinko", "--source", str(MODULES)]) == 0
    assert "JKM640N" in capsys.readouterr().out
    out = tmp_path / "o"
    code = main(
        ["cec", "export", "modules", "--all", "--source", str(MODULES), "-o", str(out), "--build"]
    )
    assert code == 0
    text = capsys.readouterr().out
    assert "built" in text and "skipped" in text and "needs review" in text
    assert len(list(out.glob("*.PAN"))) == 5


def test_cli_cec_export_requires_terms(tmp_path: Path, capsys: pytest.CaptureFixture[str]) -> None:
    code = main(["cec", "export", "inverters", "--source", str(INVERTERS), "-o", str(tmp_path)])
    assert code == 1
    assert "--all" in capsys.readouterr().err
